// General regex-based Hindi cleaner for any arbitrary text
function correctHindiText(text) {
  if (!text || typeof text !== 'string') return text;

  let s = text;

  // 1. Remove double matras and corrupted vowel sign clusters
  s = s.replace(/ूाँ/g, 'ूँ');
  s = s.replace(/ुाँ/g, 'ूँ');
  s = s.replace(/ूा/g, 'ू');
  s = s.replace(/ुा/g, 'ु');
  s = s.replace(/ााँ/g, 'ाँ');
  s = s.replace(/ाा/g, 'ा');
  s = s.replace(/ोों/g, 'ों');
  s = s.replace(/ोो/g, 'ो');
  s = s.replace(/ेे/g, 'े');
  s = s.replace(/ैै/g, 'ै');
  s = s.replace(/ीी/g, 'ी');
  s = s.replace(/ूू/g, 'ू');
  s = s.replace(/ुु/g, 'ु');

  // 2. Direct dictionary substitutions for known glitched words
  for (const [bad, good] of Object.entries(HINDI_WORD_MAP)) {
    const escaped = bad.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`(?<=^|[\\s.,!?()•*—–_])${escaped}(?=[\\s.,!?()•*—–_]|$)`, 'g');
    s = s.replace(regex, good);
  }

  // 3. Fix fragmented verbs and auxiliary endings (e.g. 'जाऊँ गा' -> 'जाऊँगा', 'ब चा' -> 'बचा')
  s = s.replace(/मारूाँ\s*गा/g, 'मारूँगा');
  s = s.replace(/मारूँ\s*गा/g, 'मारूँगा');
  s = s.replace(/जाऊँ\s*गा/g, 'जाऊँगा');
  s = s.replace(/करूँ\s*गा/g, 'करूँगा');
  s = s.replace(/बताऊँ\s*गा/g, 'बताऊँगा');
  s = s.replace(/बुलाऊँ\s*गा/g, 'बुलाऊँगा');
  s = s.replace(/खाऊँ\s*गा/g, 'खाऊँगा');
  s = s.replace(/खेलूँ\s*गा/g, 'खेलूँगा');
  s = s.replace(/होऊाँ\s*गा/g, 'होऊँगा');
  s = s.replace(/होऊँ\s*गा/g, 'होऊँगा');
  s = s.replace(/लिखो\s*गे/g, 'लिखोगे');
  s = s.replace(/खेले\s*गे/g, 'खेलेंगे');
  s = s.replace(/बनाऐ\s*गी/g, 'बनाएगी');
  s = s.replace(/चले\s*गी/g, 'चलेगी');
  s = s.replace(/खे\s+ला/g, 'खेला');
  s = s.replace(/प\s+ढ़ा/g, 'पढ़ा');
  s = s.replace(/बता\s+या/g, 'बताया');
  s = s.replace(/दल\s+खा/g, 'लिखा');
  s = s.replace(/ब\s+चा\s+है/g, 'बचा है');
  s = s.replace(/ब\s+चा/g, 'बचा');
  s = s.replace(/ब\s+ने/g, 'बने');
  s = s.replace(/व\s*हूँ/g, 'वहाँ');
  s = s.replace(/हमा\s*री/g, 'हमारी');
  s = s.replace(/बु\s*रे/g, 'बुरे');
  s = s.replace(/बु\s*री/g, 'बुरी');
  s = s.replace(/अप\s*नी/g, 'अपनी');
  s = s.replace(/थो\s*डी/g, 'थोड़ी');
  s = s.replace(/तु\s*म/g, 'तुम');
  s = s.replace(/जा\s+ना/g, 'जाना');
  s = s.replace(/आ\s+ना/g, 'आना');
  s = s.replace(/खा\s+ना/g, 'खाना');
  s = s.replace(/पी\s+ना/g, 'पीना');
  s = s.replace(/कर\s+ना/g, 'करना');
  s = s.replace(/दे\s+ना/g, 'देना');
  s = s.replace(/ले\s+ना/g, 'लेना');
  s = s.replace(/पहाँच/g, 'पहुँच');
  s = s.replace(/हआ/g, 'हुआ');
  s = s.replace(/हऐ/g, 'हुए');
  s = s.replace(/खा\s+दल\s*या/g, 'खा लिया');
  s = s.replace(/पी\s+दल\s*या/g, 'पी लिया');
  s = s.replace(/देखा\s+दल\s*या/g, 'देख लिया');
  s = s.replace(/दलया/g, 'लिया');
  s = s.replace(/दलए/g, 'लिए');
  s = s.replace(/ले\s+लों/g, 'ले लो');
  s = s.replace(/िूसरों/g, 'दूसरों');

  // 4. Broken halant+o conjuncts
  s = s.replace(/्ो(?=[\s.,!?।]|$)/g, '्ों');

  // 5. Contextual word adjustments
  // 'मै ' at word start or after space -> 'मैं '
  s = s.replace(/(^|[\s(])मै(?=[\s.,!?])/g, '$1मैं');

  // 'हाँ' when preceded by verb or auxiliary -> 'हूँ'
  s = s.replace(/(रहा|रही|रहे|करता|करती|करते|जाता|जाती|जाते|सकता|सकती|सकते|तैयार|हाँ|हूँ|हो)\s+हाँ(?=[\s.,!?।])/g, '$1 हूँ');
  s = s.replace(/(^|\s)हाँ(?=[.!?।])/g, '$1हूँ');

  // 'दक' as conjunction 'कि'
  s = s.replace(/(^|[\s])दक(?=[\s.,!?])/g, '$1कि');

  // 'दलए' -> 'लिए'
  s = s.replace(/(^|[\s])दलए(?=[\s.,!?])/g, '$1लिए');

  // 'साइदकल' -> 'साइकिल'
  s = s.replace(/साइदकल/g, 'साइकिल');

  // Specific OCR words with 'द' that should be 'ि'
  s = s.replace(/दकताब/g, 'किताब');
  s = s.replace(/दकतना/g, 'कितना');
  s = s.replace(/दकसी/g, 'किसी');
  s = s.replace(/दकस/g, 'किस');
  s = s.replace(/दकया/g, 'किया');
  s = s.replace(/दकये/g, 'किये');
  s = s.replace(/दमल/g, 'मिल');
  s = s.replace(/दलख/g, 'लिख');
  s = s.replace(/दबना/g, 'बिना');
  s = s.replace(/दचल्ला/g, 'चिल्ला');
  s = s.replace(/दचोंता/g, 'चिंता');
  s = s.replace(/दफलहाल/g, 'फिलहाल');
  s = s.replace(/दफर/g, 'फिर');
  s = s.replace(/कोदशश/g, 'कोशिश');
  s = s.replace(/मादहर/g, 'माहिर');
  s = s.replace(/भदवष्य/g, 'भविष्य');
  s = s.replace(/दवश्वास/g, 'विश्वास');
  s = s.replace(/दहसाब/g, 'हिसाब');
  s = s.replace(/दहम्मत/g, 'हिम्मत');
  s = s.replace(/दजतना/g, 'जितना');
  s = s.replace(/दनकट/g, 'निकट');
  s = s.replace(/दनकला/g, 'निकला');
  s = s.replace(/दनकली/g, 'निकली');
  s = s.replace(/दनकले/g, 'निकले');
  s = s.replace(/दनकालो/g, 'निकालो');
  s = s.replace(/दनराश/g, 'निराश');
  s = s.replace(/दबल्कुल/g, 'बिल्कुल');
  s = s.replace(/दसफज/g, 'सिर्फ');
  s = s.replace(/दसलाई/g, 'सिलाई');
  s = s.replace(/पररदचत/g, 'परिचित');
  s = s.replace(/पोदलस/g, 'पुलिस');
  s = s.replace(/पोदलश/g, 'पॉलिश');
  s = s.replace(/प्रदतभा/g, 'प्रतिभा');
  s = s.replace(/प्रदतयोदगता/g, 'प्रतियोगिता');
  s = s.replace(/लेदकन/g, 'लेकिन');
  s = s.replace(/होदशयार/g, 'होशियार');
  s = s.replace(/उत्सादहत/g, 'उत्साहित');
  s = s.replace(/चौदबसों/g, 'चौबीसों');
  s = s.replace(/जादहर/g, 'ज़ाहिर');

  // Clean double spaces
  s = s.replace(/\s+/g, ' ').replace(/\s+([.,!?।])/g, '$1').trim();

  return s;
}

